let currentLang = localStorage.getItem('feral_lang') || 'es';
const listeners = [];

export function getCurrentLang() {
  return currentLang;
}

export function onLanguageChange(callback) {
  listeners.push(callback);
}

export function setLanguage(lang) {
  if (lang !== 'es' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('feral_lang', lang);
  updateStaticTexts();

  // Notify listeners (e.g., renderCatalog)
  listeners.forEach(cb => {
    try {
      cb(currentLang);
    } catch (e) {
      console.error("Error in language change listener:", e);
    }
  });
}

export function t(key) {
  const dict = translations[currentLang] || translations.es;
  return dict[key] || key;
}

export function updateStaticTexts() {
  const dict = translations[currentLang] || translations.es;

  // Text content elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Placeholder elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update active state in language togglers
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === currentLang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Document language attribute
  document.documentElement.lang = currentLang;
}
